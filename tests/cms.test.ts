const categories: CategoryDefinition[] = [
	{ id: "security", name: "보안", parentId: null },
	{ id: "web", name: "웹", parentId: "security" },
	{ id: "sql", name: "SQL Injection", parentId: "web" },
	{ id: "practice", name: "실습", parentId: "sql" },
	{ id: "deep", name: "노트", parentId: "practice" },
	{ id: "ctf", name: "CTF", parentId: "" },
	{ id: "ctf-notes", name: "노트", parentId: "ctf" },
];

test("generated CMS selection keeps stable IDs and disambiguates arbitrary-depth names", () => {
	const config = createCmsConfig(categories);
	const posts = config.content.find((entry) => entry.name === "posts");
	const values = posts.fields.find((field) => field.name === "categoryId")
		.options.values;
	assert.deepEqual(
		values.find((item) => item.name === "deep"),
		{ name: "deep", label: "보안 / 웹 / SQL Injection / 실습 / 노트" },
	);
	assert.deepEqual(
		values.find((item) => item.name === "ctf-notes"),
		{ name: "ctf-notes", label: "CTF / 노트" },
	);
	assert.equal(
		posts.fields.find((field) => field.name === "categoryId").options.multiple,
		false,
	);
	const moved = categories.map((entry) =>
		entry.id === "deep"
			? { ...entry, name: "새 이름", parentId: "ctf" }
			: entry,
	);
	assert.equal(
		createCmsConfig(moved)
			.content[0].fields.find((field) => field.name === "categoryId")
			.options.values.find((item) => item.name === "deep").label,
		"CTF / 새 이름",
	);
	assert.equal(
		categories[0].parentId,
		null,
		"normalization must not mutate the single source",
	);
	const samePaths = createCmsConfig([
		{ id: "a", name: "동명" },
		{ id: "b", name: "동명" },
		{ id: "a-leaf", name: "노트", parentId: "a" },
		{ id: "b-leaf", name: "노트", parentId: "b" },
	]).content[0].fields.find((field) => field.name === "categoryId").options
		.values;
	assert.equal(
		samePaths.find((value) => value.name === "a-leaf").label,
		"동명 / 노트 [a-leaf]",
	);
	assert.equal(
		samePaths.find((value) => value.name === "b-leaf").label,
		"동명 / 노트 [b-leaf]",
	);
});

test("generated configuration is deterministic valid YAML and catches stale or manually altered output", () => {
	const document = renderCmsConfig(categories);
	assert(document.startsWith("# Generated by pnpm cms:sync"));
	assert(
		document.split("\n").length > 20,
		"header must end with real newlines",
	);
	const plugin = yaml();
	assert(
		plugin.transform.call({}, document, ".pages.yml"),
		"existing YAML parser accepts generated JSON notation",
	);
	assert.equal(
		renderCmsConfig([...categories].reverse()),
		document,
		"input row order does not change sorted choices",
	);
	checkCmsConfig(document, categories);
	assert.throws(
		() => checkCmsConfig(document.replace("보안", "변조"), categories),
		/CMS_CONFIG_STALE/,
	);
	assert.throws(
		() => createCmsConfig([...categories, { id: "security", name: "중복" }]),
		/CATEGORY_DUPLICATE_ID/,
	);
});

test("CMS form policies preserve Markdown, nested posts, safe image paths and new drafts", () => {
	const config = createCmsConfig(categories);
	const posts = config.content[0];
	const fields = new Map(posts.fields.map((field) => [field.name, field]));
	assert.equal(posts.path, "src/content/posts");
	assert.equal(posts.subfolders, true);
	assert.deepEqual(posts.filename, {
		template: "{fields.slug}.md",
		field: "create",
	});
	assert.equal(posts.operations.rename, false);
	assert.equal(fields.get("draft").default, true);
	assert.equal(fields.get("body").type, "rich-text");
	assert.equal(fields.get("body").options.format, "markdown");
	assert.equal(fields.get("body").options.switcher, true);
	assert.equal(config.media[0].input, "public/images");
	assert.equal(config.media[0].output, "/images");
	assert(!config.media[0].extensions.includes("avif"));
	assert(
		!config.media[0].extensions.includes("svg"),
		"arbitrary uploaded SVG is not in the CMS allowlist",
	);
	assert.equal(config.content[1].list, true);
	assert.deepEqual(
		config.content[1].fields.map((field) => field.name),
		["id", "name", "parentId", "order"],
	);
});

test("CMS dates accept only genuine Date or calendar-valid day strings", () => {
	const date = new Date("2024-02-29T00:00:00.000Z");
	assert.equal(normalizeContentDate(date), date);
	assert.equal(
		(normalizeContentDate("2024-02-29") as Date).toISOString(),
		date.toISOString(),
	);
	for (const value of [
		"2023-02-29",
		"2026-04-31",
		"2026-13-01",
		"2026-00-10",
		"",
		null,
		true,
		false,
		0,
		20261023,
		"yesterday",
	]) {
		assert(
			!(normalizeContentDate(value) instanceof Date),
			`do not coerce ${JSON.stringify(value)}`,
		);
	}
	assert.equal(normalizeContentDate("", true), undefined);
	assert.equal(normalizeContentDate(undefined, true), undefined);
	assert.equal(
		normalizeContentDate(null, true),
		null,
		"null is not silently interpreted as an absent optional date",
	);
});

test("CMS category root representations normalize without accepting malformed graph fields", () => {
	const tree = createTaxonomy(categories, []);
	assert.deepEqual(
		tree.children.get(undefined)?.map((entry) => entry.id),
		["ctf", "security"],
	);
	for (const [value, field] of [
		[null, "categories.json"],
		[[null], "[0]"],
		[[{ id: 1, name: "a" }], ".id"],
		[[{ id: "a", name: null }], ".name"],
		[[{ id: "a", name: "a", parentId: 3 }], ".parentId"],
		[[{ id: "a", name: "a", order: null }], ".order"],
	] as const) {
		assert.throws(
			() => createTaxonomy(value as unknown as CategoryDefinition[], []),
			(error: Error) => error.message.includes(field),
		);
	}
	assert.throws(
		() => createTaxonomy([{ id: "a", name: "a", parentId: "a" }], []),
		/CATEGORY_CYCLE/,
	);
});

const context = {
	repository: "synthetic-owner/synthetic-blog",
	ref: "refs/heads/main",
};
const payload = {
	source: "pages-cms",
	action: { name: "publish-blog" },
	repository: {
		owner: "synthetic-owner",
		repo: "synthetic-blog",
		ref: "main",
		workflowRef: "main",
	},
	triggeredBy: { email: "synthetic@example.invalid" },
};
test("CMS action validates actual main and exact action/repository context, not claimed user identity", () => {
	assert.equal(
		validateCmsPayload(JSON.stringify(payload), context),
		"publish-blog",
	);
	assert.equal(
		validateCmsPayload(
			JSON.stringify({ ...payload, action: { name: "refresh-categories" } }),
			context,
		),
		"refresh-categories",
	);
	assert.throws(
		() =>
			validateCmsPayload(JSON.stringify(payload), {
				...context,
				ref: "refs/heads/other",
			}),
		/MAIN_ONLY/,
	);
	assert.throws(() => validateCmsPayload("invalid", context), /INVALID_JSON/);
	assert.throws(
		() =>
			validateCmsPayload(
				JSON.stringify({ ...payload, action: { name: "shell" } }),
				context,
			),
		/UNSUPPORTED/,
	);
	assert.throws(
		() =>
			validateCmsPayload(
				JSON.stringify({
					...payload,
					repository: { ...payload.repository, repo: "other" },
				}),
				context,
			),
		/WRONG_REPOSITORY/,
	);
	assert.throws(
		() =>
			validateCmsPayload(
				JSON.stringify({
					...payload,
					repository: { ...payload.repository, ref: "preview" },
				}),
				context,
			),
		/WRONG_REF/,
	);
});

test("CMS action CLI emits a real output line without exposing the contextual user", () => {
	const output = "artifacts/cms-action-output.txt";
	const event = "artifacts/cms-action-test-event.json";
	const before = existsSync(output) ? readFileSync(output) : undefined;
	try {
		mkdirSync("artifacts", { recursive: true });
		writeFileSync(
			event,
			JSON.stringify({ inputs: { payload: JSON.stringify(payload) } }),
		);
		const result = spawnSync(
			process.execPath,
			["--experimental-strip-types", "scripts/cms-action.mjs"],
			{
				encoding: "utf8",
				env: {
					...process.env,
					GITHUB_EVENT_PATH: event,
					GITHUB_REPOSITORY: context.repository,
					GITHUB_REF: context.ref,
				},
			},
		);
		assert.equal(result.status, 0, result.stderr);
		assert.equal(readFileSync(output, "utf8"), "action=publish-blog\n");
		assert(!result.stdout.includes("synthetic@example.invalid"));
		const rejected = spawnSync(
			process.execPath,
			["--experimental-strip-types", "scripts/cms-action.mjs"],
			{
				encoding: "utf8",
				env: {
					...process.env,
					GITHUB_EVENT_PATH: event,
					GITHUB_REPOSITORY: context.repository,
					GITHUB_REF: "refs/heads/preview",
				},
			},
		);
		assert.notEqual(rejected.status, 0);
		assert(
			!`${rejected.stdout}${rejected.stderr}`.includes(
				"synthetic@example.invalid",
			),
		);
		writeFileSync(event, '{"synthetic@example.invalid": invalid');
		const malformed = spawnSync(
			process.execPath,
			["--experimental-strip-types", "scripts/cms-action.mjs"],
			{
				encoding: "utf8",
				env: { ...process.env, GITHUB_EVENT_PATH: event },
			},
		);
		assert.notEqual(malformed.status, 0);
		assert.match(malformed.stderr, /CMS_ACTION_EVENT_UNREADABLE/);
		assert(
			!`${malformed.stdout}${malformed.stderr}`.includes(
				"synthetic@example.invalid",
			),
		);
	} finally {
		rmSync(event, { force: true });
		if (before) writeFileSync(output, before);
		else rmSync(output, { force: true });
	}
});
